// Run before publishing: node scripts/stamp.mjs
// Adds content hashes to everything index.html loads, so browsers never serve a stale copy:
//   - stylesheet, icons and the entry script get ?v=<hash>
//   - every JS module goes into an import map, so imports between modules carry their own hash too
//   - og:image / twitter:image get the hash of og.png
// Only the <!-- stamp --> … <!-- /stamp --> block and the og.png query strings in index.html are rewritten.
import { readFileSync, writeFileSync, readdirSync } from "node:fs";
import { createHash } from "node:crypto";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const hash = (f) => createHash("sha1").update(readFileSync(join(root, f))).digest("hex").slice(0, 10);
const v = (f) => `${f}?v=${hash(f)}`;

const js = readdirSync(join(root, "src"))
  .filter((n) => n.endsWith(".js"))
  .sort()
  .map((n) => `src/${n}`);
const imports = Object.fromEntries(js.map((f) => [`./${f}`, `./${v(f)}`]));

const block = [
  "<!-- stamp: generated by scripts/stamp.mjs, do not edit by hand -->",
  `<link rel="icon" type="image/svg+xml" href="${v("assets/icon.svg")}">`,
  `<link rel="icon" type="image/png" sizes="32x32" href="${v("assets/icon-32.png")}">`,
  `<link rel="apple-touch-icon" sizes="180x180" href="${v("assets/apple-touch-icon.png")}">`,
  `<link rel="stylesheet" href="${v("src/style.css")}">`,
  `<script type="importmap">${JSON.stringify({ imports }, null, 1)}</script>`,
  `<script type="module" src="${v("src/main.js")}"></script>`,
].join("\n");

const file = join(root, "index.html");
let html = readFileSync(file, "utf8");
const re = /<!-- stamp -->[\s\S]*?<!-- \/stamp -->/;
if (!re.test(html)) throw new Error("index.html has no <!-- stamp --> block");
html = html.replace(re, `<!-- stamp -->\n${block}\n<!-- /stamp -->`);
html = html.replace(/og\.png\?v=[^"]*/g, `og.png?v=${hash("og.png")}`);
writeFileSync(file, html);
console.log(`stamped ${js.length} modules, style.css, icons and og.png`);
