/* 趣味耳朵年齡：最高可聽頻率 → 寬鬆的年齡區間
 *
 * 參考資料怎麼分：
 * 研究資料
 *   - ISO 7029:2017 只整理到 8 kHz，沒有 8 kHz 以上的年齡標準。
 *   - 延伸高頻（9–20 kHz）聽閾研究，例如 Rodríguez Valiente et al., 2014,
 *     Int J Audiol 53(8)，645 位健康受試者：高頻聽閾隨年齡明顯上升，
 *     且越高的頻率越早開始退化；但個體差異很大，同齡人可差上數千 Hz。
 *   - 這些研究用校正過的耳機與「聽閾 dB」量測，本網頁只有固定的低音量、
 *     未校正的耳機或喇叭，量不到聽閾，只能看「這個音量下還聽不聽得到」。
 * 網路流傳的對照表（「蚊子音」測驗）
 *   - 常見寫法：17.4k 以上 < 24 歲、16k < 30、15k < 40、14k < 50、12k < 60…
 *     沒有可追溯的研究來源，只有大致趨勢與研究方向一致。
 *
 * 所以這裡只給「大約幾十歲」的寬鬆區間，趨勢參考研究方向、
 * 分界參考流傳表並再放寬，明確當成趣味換算，不是測量結果。
 * min 是頻率下限（Hz），由高到低排列，第一個符合的就是結果。 */
export const AGE_BANDS = [
  { min: 17000, age: '大約 20 歲以下', lines: ['蚊子還沒完全贏過你。', '蚊子看到你都想繞路。'] },
  { min: 16000, age: '大約 20 多歲',   lines: ['你比想像中更能撐。', '這一局，你跟蚊子平手。'] },
  { min: 15000, age: '大約 30 歲上下', lines: ['蚊子還沒完全贏過你。', '高頻世界還歡迎你。'] },
  { min: 14000, age: '大約 30 多歲',   lines: ['高頻世界向你揮手告別。', '蚊子開始佔上風了。'] },
  { min: 12500, age: '大約 40 多歲',   lines: ['這一局，蚊子勝。', '蚊子先溜走了。'] },
  { min: 10000, age: '大約 50 多歲',   lines: ['你的耳朵決定下班了。', '耳朵很懂得取捨。'] },
  { min: 7000,  age: '大約 60 歲上下', lines: ['耳朵已經舉白旗了。', '安靜，也是一種享受。'] },
  { min: 0,     age: '資深耳朵',       lines: ['耳朵已經舉白旗了。', '世界清靜了不少。'] },
];

/* 一路撐到測試上限：不能當成真正的極限 */
export const LIMIT = { age: '測試先投降了', lines: ['測試先舉白旗了。', '這台機器追不上你。'] };

/* 海報上的動物＝停下來那個頻率的動物（見 config.js 的 STAGES） */
export function ageFor(hz, isLimit) {
  const b = isLimit ? LIMIT : AGE_BANDS.find(b => hz >= b.min);
  return { ...b, line: b.lines[Math.floor(Math.random() * b.lines.length)] };
}
