import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import {parseCSV,normalize,validDate,taipeiDate,average,summary,ratio,percentile,period,monthly,daysOfYear,level} from '../data-core.mjs';
let count=0;function test(name,fn){fn();count++;console.log('PASS '+name);}
const header='date,aircraft_total,median_line_cross,ships_total,special_event\n';
const csv=header+'2024-01-01,0,0,3,"逗號,與""引號"""\n2024-01-03,10,5,,\n2024-02-01,,0,2,\n';
const rows=normalize(csv,'2026-11-16');
test('CSV quoted commas and escaped quotes',()=>assert.equal(rows[0].note,'逗號,與"引號"'));
test('CSV embedded newline',()=>assert.equal(parseCSV(header+'2024-01-01,0,0,0,"a\nb"')[0].special_event,'a\nb'));
test('BOM and CRLF',()=>assert.equal(normalize('\uFEFF'+header.replace('\n','\r\n')+'2024-01-01,0,0,0,\r\n','2026-11-16').length,1));
test('unclosed quotes rejected',()=>assert.throws(()=>parseCSV(header+'"x')));
test('schema changes rejected',()=>assert.throws(()=>normalize('date,total\n2024-01-01,2','2026-11-16')));
test('leap day valid',()=>assert.equal(validDate('2024-02-29'),true));
test('invalid dates rejected',()=>assert.equal(validDate('2023-02-29'),false));
test('future dates rejected',()=>assert.throws(()=>normalize(header+'2027-01-01,0,0,0,','2026-11-16')));
test('Taipei midnight conversion',()=>assert.equal(taipeiDate(new Date('2026-11-15T16:01:00Z')),'2026-11-16'));
test('missing stays null',()=>assert.equal(rows[1].ships_total,null));
test('zero stays zero',()=>assert.equal(rows[0].aircraft_total,0));
test('missing day never manufactured',()=>assert.equal(rows.length,3));
test('negative values rejected',()=>assert.throws(()=>normalize(header+'2024-01-01,-1,0,0,','2026-11-16')));
test('fractional values rejected',()=>assert.throws(()=>normalize(header+'2024-01-01,1.5,0,0,','2026-11-16')));
test('cross exceeds aircraft rejected',()=>assert.throws(()=>normalize(header+'2024-01-01,1,2,0,','2026-11-16')));
test('duplicate date rejected',()=>assert.throws(()=>normalize(header+'2024-01-01,1,0,0,\n2024-01-01,1,0,0,','2026-11-16')));
test('annual valid counts and sum',()=>assert.deepEqual([summary(rows,'aircraft_total').days,summary(rows,'aircraft_total').total],[2,10]));
test('monthly counts',()=>assert.deepEqual(monthly(rows,2024,'aircraft_total').slice(0,2).map(s=>s.days),[2,0]));
test('average excludes null but includes zero',()=>assert.equal(average(rows,'aircraft_total'),5));
test('7 valid observations',()=>{const a=Array.from({length:12},(_,i)=>({x:i}));a[10].x=null;assert.equal(average(a,'x',7),(4+5+6+7+8+9+11)/7);});
test('30 valid observations',()=>assert.equal(average(Array.from({length:40},(_,i)=>({x:i+1})),'x',30),25.5));
test('empty average null',()=>assert.equal(average([],'x'),null));
test('percentile uses strict less than',()=>assert.equal(percentile(rows,'aircraft_total',10),50));
test('percentile null handling',()=>assert.equal(percentile(rows,'aircraft_total',null),null));
test('zero denominator ratio null',()=>assert.equal(ratio(rows[0]),null));
test('cross ratio',()=>assert.equal(ratio(rows[1]),.5));
test('same period cutoff',()=>assert.equal(period(rows,2024,'01-02').length,1));
test('leap year calendar',()=>assert.equal(daysOfYear(2024).length,366));
test('missing is separate scale',()=>assert.equal(level(null,'aircraft_total'),-1));
test('zero is first scale',()=>assert.equal(level(0,'aircraft_total'),0));
test('historical correction replaces value',()=>assert.equal(normalize(csv.replace('10,5','12,5'),'2026-11-16')[1].aircraft_total,12));
const real=JSON.parse(await fs.readFile(new URL('../data/records.json',import.meta.url),'utf8'));
test('real data count matches metadata',()=>assert.equal(real.records.length,real.count));
test('real data is chronologically ordered',()=>assert.ok(real.records.every((r,i)=>!i||r.date>real.records[i-1].date)));
test('latest matches final record',()=>assert.equal(real.latest,real.records.at(-1).date));
test('real statistics match recomputation',()=>assert.equal(real.statistics.aircraft_total.total,summary(real.records,'aircraft_total').total));
console.log(`${count} tests passed`);
