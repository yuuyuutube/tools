import { cp, mkdir, readFile, rm, writeFile } from 'node:fs/promises';
const root = new URL('../', import.meta.url);
const output = new URL('dist/', root);
// These small modules form a single dependency-ordered scope. Generate a classic
// script so the tool also works when index.html is opened directly via file://.
// Source modules remain separately testable; unsupported module syntax fails here.
const modules = ['pitch', 'audio', 'instrument', 'visualization', 'app'];
const chunks = [];
for (const name of modules) {
  const source = await readFile(new URL(`src/${name}.js`, root), 'utf8');
  const code = source.replace(/^import \{[^\n]+\} from ['"]\.\/[^'"]+['"];\r?\n/gm, '')
    .replace(/^export (?=(?:const|let|function|class)\b)/gm, '');
  if (/^\s*(?:import|export)\b/m.test(code)) throw new Error(`Unsupported module syntax in ${name}.js`);
  chunks.push(`// src/${name}.js\n${code}`);
}
const bundle = `// Generated by scripts/build.mjs. Edit src/, then rebuild.\n(() => {\n'use strict';\n${chunks.join('\n')}\n})();\n`;
await writeFile(new URL('app.bundle.js', root), bundle);
await rm(output, { recursive: true, force: true });
await mkdir(output, { recursive: true });
for (const path of ['index.html', 'app.bundle.js', 'assets']) await cp(new URL(path, root), new URL(path, output), { recursive: true });
await mkdir(new URL('src/', output), { recursive: true });
await cp(new URL('src/styles.css', root), new URL('src/styles.css', output));
await writeFile(new URL('.nojekyll', output), '');
console.log('Built app.bundle.js and dist/: works over HTTPS and file://.');
