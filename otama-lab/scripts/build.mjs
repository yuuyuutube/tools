import { cp, mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
const root = new URL('../', import.meta.url);
const output = new URL('dist/', root);
// Each entry has a small dependency-ordered scope. Classic scripts also let the
// virtual tool run via file://. Microphone / Worker use HTTPS or localhost.
// Source modules remain separately testable; unsupported module syntax fails here.
async function bundleModules(modules) {
  const chunks = [];
  for (const name of modules) {
    const source = await readFile(new URL(`src/${name}.js`, root), 'utf8');
    const code = source.replace(/^import \{[^\n]+\} from ['"]\.{1,2}\/[^'"]+['"];\r?\n/gm, '')
      .replace(/^export (?=(?:const|let|function|class|async function)\b)/gm, '');
    if (/^\s*(?:import|export)\b/m.test(code)) throw new Error(`Unsupported module syntax in ${name}.js`);
    chunks.push(`// src/${name}.js\n${code}`);
  }
  return `// Generated by scripts/build.mjs. Edit src/, then rebuild.\n(() => {\n'use strict';\n${chunks.join('\n')}\n})();\n`;
}
const bundle = await bundleModules(['pitch', 'audio', 'instrument', 'visualization', 'focus', 'app']);
await writeFile(new URL('app.bundle.js', root), bundle);
// Pages/browser caches must not mix a new neck direction with an older script.
const versionOf = source => createHash('sha256').update(source).digest('hex').slice(0, 12);
const css = await readFile(new URL('src/styles.css', root), 'utf8');
const htmlPath = new URL('index.html', root);
const html = (await readFile(htmlPath, 'utf8'))
  .replace(/src="\.\/app\.bundle\.js(?:\?v=[a-f0-9]+)?"/, `src="./app.bundle.js?v=${versionOf(bundle)}"`)
  .replace(/href="\.\/src\/styles\.css(?:\?v=[a-f0-9]+)?"/, `href="./src/styles.css?v=${versionOf(css)}"`);
await writeFile(htmlPath, html);
const worker = await bundleModules(['analysis/yin', 'analysis/pitch-worker']);
await writeFile(new URL('pitch-worker.js', root), worker);
const live = (await bundleModules(['pitch', 'input/microphone', 'analysis/stability', 'live/timeline', 'live/recording', 'live/format', 'live/export', 'live/playback', 'live/replay', 'live/focus', 'live/capture', 'live/mini-otama', 'live/app']))
  .replace("'./pitch-worker.js'", `'./pitch-worker.js?v=${versionOf(worker)}'`);
await writeFile(new URL('live.bundle.js', root), live);
const liveCss = await readFile(new URL('src/live/styles.css', root), 'utf8');
const liveHtmlPath = new URL('live.html', root);
const liveHtml = (await readFile(liveHtmlPath, 'utf8'))
  .replace(/src="\.\/live\.bundle\.js(?:\?v=[a-f0-9]+)?"/, `src="./live.bundle.js?v=${versionOf(live)}"`)
  .replace(/href="\.\/src\/styles\.css(?:\?v=[a-f0-9]+)?"/, `href="./src/styles.css?v=${versionOf(css)}"`)
  .replace(/href="\.\/src\/live\/styles\.css(?:\?v=[a-f0-9]+)?"/, `href="./src/live/styles.css?v=${versionOf(liveCss)}"`);
await writeFile(liveHtmlPath, liveHtml);
const wah = await bundleModules(['pitch', 'wah/audio', 'wah/input', 'wah/spectrum', 'wah/keyboard', 'wah/focus', 'wah/app']);
await writeFile(new URL('wah.bundle.js', root), wah);
const wahCss = await readFile(new URL('src/wah/styles.css', root), 'utf8');
const wahHtmlPath = new URL('wah.html', root);
const wahHtml = (await readFile(wahHtmlPath, 'utf8'))
  .replace(/src="\.\/wah\.bundle\.js(?:\?v=[a-f0-9]+)?"/, `src="./wah.bundle.js?v=${versionOf(wah)}"`)
  .replace(/href="\.\/src\/styles\.css(?:\?v=[a-f0-9]+)?"/, `href="./src/styles.css?v=${versionOf(css)}"`)
  .replace(/href="\.\/src\/wah\/styles\.css(?:\?v=[a-f0-9]+)?"/, `href="./src/wah/styles.css?v=${versionOf(wahCss)}"`);
await writeFile(wahHtmlPath, wahHtml);
await rm(output, { recursive: true, force: true });
await mkdir(output, { recursive: true });
for (const path of ['index.html', 'live.html', 'wah.html', 'app.bundle.js', 'live.bundle.js', 'wah.bundle.js', 'pitch-worker.js', 'assets']) await cp(new URL(path, root), new URL(path, output), { recursive: true });
await mkdir(new URL('src/live/', output), { recursive: true });
await cp(new URL('src/styles.css', root), new URL('src/styles.css', output));
await cp(new URL('src/live/styles.css', root), new URL('src/live/styles.css', output));
await mkdir(new URL('src/wah/', output), { recursive: true });
await cp(new URL('src/wah/styles.css', root), new URL('src/wah/styles.css', output));
await writeFile(new URL('.nojekyll', output), '');
console.log('Built virtual / live / wah bundles, pitch worker and dist/. Live microphone needs HTTPS or localhost.');
